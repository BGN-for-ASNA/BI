"""Generate fixtures/input.json for the bayesplot PPC cross-check tests.

Writes a shared fixture consumed by make_reference.R (R/bayesplot side) and
the pytest module (BayesForge side). Stdlib json + numpy only.

Run from the repo root:
    cd /home/sosa/work/BF && PYTHONPATH=$PWD \
        /home/sosa/work/3.12venv/bin/python Test/2.Diagnostic_plots/make_input.py
"""

import json
import math
import os

import numpy as np

SEED = 20261022
N_OBS = 30
N_REP = 200

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_PATH = os.path.join(HERE, "fixtures", "input.json")


def r6(v):
    """Round a float to 6 decimals for JSON output."""
    return float(round(float(v), 6))


def main():
    rng = np.random.default_rng(SEED)

    # Shared covariate
    x = rng.normal(size=N_OBS)

    # --- Continuous case ---
    y = rng.normal(loc=1.0 + 0.5 * x, scale=1.0)
    yrep = rng.normal(loc=1.1 + 0.5 * x, scale=1.3, size=(N_REP, N_OBS))

    # Log-likelihood: log_lik[s, i] = log N(y_i | 1.0 + 0.5*x_i + eps_s, 1.0)
    eps = rng.normal(0.0, 0.1, N_REP)
    mu = 1.0 + 0.5 * x  # (N_OBS,)
    # log N(y_i | mu_i + eps_s, 1.0) = -0.5*log(2*pi) - 0.5*(y_i - mu_i - eps_s)^2
    resid = y[None, :] - (mu[None, :] + eps[:, None])
    log_lik = -0.5 * math.log(2.0 * math.pi) - 0.5 * resid ** 2

    # --- Count case (same x) ---
    lam_obs = 3.0 * np.exp(0.2 * x)
    lam_rep = 3.3 * np.exp(0.2 * x)
    y_count = rng.poisson(lam=lam_obs).astype(int)
    yrep_count = rng.poisson(lam=lam_rep, size=(N_REP, N_OBS)).astype(int)

    data = {
        "meta": {
            "seed": SEED,
            "n_obs": N_OBS,
            "n_rep": N_REP,
            "description": (
                "Shared PPC fixture: continuous Normal y/yrep/log_lik and "
                "count Poisson y/yrep on a common covariate x; "
                "generated by make_input.py with numpy default_rng."
            ),
        },
        "continuous": {
            "y": [r6(v) for v in y],
            "yrep": [[r6(v) for v in row] for row in yrep],
            "log_lik": [[r6(v) for v in row] for row in log_lik],
        },
        "count": {
            "y": [int(v) for v in y_count],
            "yrep": [[int(v) for v in row] for row in yrep_count],
        },
        "x": [r6(v) for v in x],
    }

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w") as f:
        json.dump(data, f, indent=None)

    size = os.path.getsize(OUT_PATH)
    print(f"wrote {OUT_PATH}")
    print(f"continuous y: len={len(data['continuous']['y'])}")
    print(f"continuous yrep: shape=({len(data['continuous']['yrep'])}, "
          f"{len(data['continuous']['yrep'][0])})")
    print(f"continuous log_lik: shape=({len(data['continuous']['log_lik'])}, "
          f"{len(data['continuous']['log_lik'][0])})")
    print(f"count y: len={len(data['count']['y'])}, "
          f"yrep shape=({len(data['count']['yrep'])}, {len(data['count']['yrep'][0])})")
    print(f"file size: {size} bytes")


if __name__ == "__main__":
    main()
