# 11. ppc_bars (bayesplot ppc_bars_data, prob=0.9, freq=TRUE)
# ---------------------------------------------------------------------------

def test_ppc_bars():
    fig = ppc.ppc_bars(CY, CYREP)
    obs, rep = fig.data
    ref = RCOUNT["bars"]
    np.testing.assert_allclose(np.asarray(obs.x, float), np.array(ref["xpos"]),
                               rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(np.asarray(obs.y, float), np.array(ref["observed"]),
                               rtol=RTOL, atol=ATOL)
    pt = np.asarray(rep.y, dtype=float)
    # BF's point is the MEDIAN count -> matches the reference yrep_median exactly
    np.testing.assert_allclose(pt, np.array(ref["yrep_median"]), rtol=RTOL, atol=ATOL)
    # error bars recover the 5%/95% type-7 count quantiles (match bayesplot l/h)
    lo = pt - np.asarray(rep.error_y.arrayminus, dtype=float)
    hi = pt + np.asarray(rep.error_y.array, dtype=float)
    np.testing.assert_allclose(lo, np.array(ref["yrep_q05"]), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(hi, np.array(ref["yrep_q95"]), rtol=RTOL, atol=ATOL)


def test_ppc_bars_point_is_median():
    fig = ppc.ppc_bars(CY, CYREP)
    pt = np.asarray(fig.data[1].y, dtype=float)
    np.testing.assert_allclose(pt, np.array(RCOUNT["bars"]["yrep_median"]),
                               rtol=RTOL, atol=ATOL)


# ---------------------------------------------------------------------------
# 12. ppc_loo_pit with log_likelihood (bayesplot ppc_loo_pit_data via
#     rstantools::loo_pit / loo::psis_loo).  ppc_loo_pit(log_likelihood=LL)
#     uses reff=None -> 1.0, matching the reference's r_eff = 1.  The figure
#     exposes only the PIT density (last trace), so the PIT vector is recomputed through the
#     same _psis_weights code path ppc_loo_pit calls, and tied to the figure
#     by checking the plotted density is the reflected Scott KDE of it.
# ---------------------------------------------------------------------------

def _loo_pit_figure_and_pit():
    fig = ppc.ppc_loo_pit(Y, YREP, log_likelihood=LL)
    pit = _bf_loo_pit()
    grid = np.asarray(fig.data[-1].x, dtype=float)
    np.testing.assert_allclose(grid, np.linspace(0.0, 1.0, 300), rtol=0, atol=0)
    # the figure's PIT density is built from exactly these PIT values
    np.testing.assert_allclose(np.asarray(fig.data[-1].y, dtype=float),
                               _reflected_kde_1d(pit, grid), rtol=RTOL, atol=ATOL)
    return pit


def test_ppc_loo_pit_matches_reference_pit_loo():
    pit = _loo_pit_figure_and_pit()
    np.testing.assert_allclose(pit, np.array(RC["loo_pit"]["pit_loo"]),
                               rtol=RTOL, atol=ATOL)


def test_ppc_loo_pit_matches_pit_rstantools():
    pit = _loo_pit_figure_and_pit()
    # BayesForge's ArviZ-style PSIS (_psis_weights) and loo::psis (behind
    # rstantools::loo_pit) are different implementations; their PIT values
    # differ by ~1.2e-8, which the suite tolerance (rtol=1e-7, atol=1e-9)
    # covers.
    np.testing.assert_allclose(pit, np.array(RC["loo_pit"]["pit_rstantools"]),
                               rtol=RTOL, atol=ATOL)


# ---------------------------------------------------------------------------
# 13. ppc_loo_pit WITHOUT log_likelihood: plain PIT mean(yrep <= y) per
#     observation (must pass; reference pit_plain and recomputed from arrays).
# ---------------------------------------------------------------------------

def test_ppc_loo_pit_without_loglik_is_plain_pit():
    with pytest.warns(UserWarning, match="without log_likelihood"):
        fig = ppc.ppc_loo_pit(Y, YREP)
    pit = np.array([np.mean(YREP[:, i] <= Y[i]) for i in range(len(Y))])
    np.testing.assert_allclose(pit, np.array(RC["loo_pit"]["pit_plain"]),
                               rtol=RTOL, atol=ATOL)
    # the figure's PIT density is built from exactly these plain PIT values
    grid = np.asarray(fig.data[-1].x, dtype=float)
    np.testing.assert_allclose(grid, np.linspace(0.0, 1.0, 300), rtol=0, atol=0)
    np.testing.assert_allclose(np.asarray(fig.data[-1].y, dtype=float),
                               _reflected_kde_1d(pit, grid), rtol=RTOL, atol=ATOL)
