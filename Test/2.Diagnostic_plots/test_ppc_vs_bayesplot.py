# 3. intervals sorted by y (bayesplot ppc_intervals_data on rows sorted by y)
# ---------------------------------------------------------------------------

def test_ppc_intervals_sorted_matches_bayesplot():
    # the reference was computed with prob = prob_outer = 0.9
    fig = ppc.ppc_intervals_sorted(Y, YREP, prob=0.9)
    # reference rows are in R order(y) order; compare in the same order
    ll, l, m, h, hh, obs = _interval_bounds(fig)
    np.testing.assert_allclose(obs, np.sort(Y), rtol=RTOL, atol=ATOL)
    ref = RC["intervals_sorted"]
    np.testing.assert_allclose(ll, np.array(ref["ll"]), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(l, np.array(ref["l"]), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(m, np.array(ref["m"]), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(h, np.array(ref["h"]), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(hh, np.array(ref["hh"]), rtol=RTOL, atol=ATOL)


# ---------------------------------------------------------------------------
# 4. ppc_stat (bayesplot ppc_stat_data: T(y) and T(yrep) per draw)
#
# The figure exposes T(y) exactly as the add_vline x0 (layout shape) and the
# T(yrep) vector only through its range: the KDE trace's x grid is
# np.linspace(T(yrep).min(), T(yrep).max(), 300), whose endpoints equal
# min/max of the 200 per-draw statistics exactly.
# ---------------------------------------------------------------------------

def _check_stat(stat, ref_y, ref_rep):
    fig = ppc.ppc_stat(Y, YREP, stat=stat)
    np.testing.assert_allclose(fig.layout.shapes[0].x0, ref_y, rtol=RTOL, atol=ATOL)
    grid = np.asarray(fig.data[0].x, dtype=float)
    ref_rep = np.asarray(ref_rep, dtype=float)
    np.testing.assert_allclose(grid[0], ref_rep.min(), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(grid[-1], ref_rep.max(), rtol=RTOL, atol=ATOL)


def test_ppc_stat_mean():
    _check_stat("mean", RC["stat_mean_y"], RC["stat_mean_yrep"])


def test_ppc_stat_sd():
    # BF's "sd" is np.std(ddof=1) == R's sd
    _check_stat("sd", RC["stat_sd_y"], RC["stat_sd_yrep"])


