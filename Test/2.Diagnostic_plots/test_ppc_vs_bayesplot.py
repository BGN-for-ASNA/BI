"""Cross-check BayesForge PPC plots (BayesForge/Diagnostic/ppc.py) against the
R bayesplot 1.16.0 reference numbers in fixtures/reference.json (generated by
make_reference.R from the same fixtures/input.json arrays; R is NOT called at
test time).

Tolerances: rtol=1e-7, atol=1e-9 are used for every quantity that is exact
arithmetic -- R's stats::quantile(type = 7) is the same linear-interpolation
percentile as np.percentile, and both sides read the *same* JSON fixture
arrays, so the only possible discrepancy is floating-point summation/order
noise (~1e-15 here).  Anything that fails at these tolerances is therefore a
genuine algorithmic difference between BayesForge and bayesplot, not rounding;
such tests are marked xfail(strict=True) with the precise reason (quantity,
max abs difference, and what ppc.py does differently).  The two LOO-PIT
comparisons are not exact arithmetic (different PSIS implementations), but
their difference (~1.2e-8) is covered by the suite tolerance, so they pass.

Each test calls the BayesForge function directly with the fixture arrays and
extracts the numbers from the returned plotly figure (fig.data traces' x/y,
Bar.base, Scatter.error_y, or the ppc_stat vline in fig.layout.shapes).
"""
import json
import os

import numpy as np
import pytest

from BayesForge.Diagnostic import ppc
from BayesForge.Diagnostic.jax_diagnostics import _psis_weights

RTOL = 1e-7
ATOL = 1e-9

_HERE = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(_HERE, "fixtures", "input.json")) as _f:
    INP = json.load(_f)
with open(os.path.join(_HERE, "fixtures", "reference.json")) as _f:
    REF = json.load(_f)

Y = np.array(INP["continuous"]["y"], dtype=float)          # (30,)
YREP = np.array(INP["continuous"]["yrep"], dtype=float)    # (200, 30)
LL = np.array(INP["continuous"]["log_lik"], dtype=float)   # (200, 30)
X = np.array(INP["x"], dtype=float)                        # (30,)
CY = np.array(INP["count"]["y"])                           # (30,) ints
CYREP = np.array(INP["count"]["yrep"])                     # (200, 30) ints

RC = REF["continuous"]
RCOUNT = REF["count"]
RESID = np.array(RC["error_hist_resid"], dtype=float)      # (200, 30) per-draw y - yrep


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _interval_bounds(fig):
    """Extract (ll, l, m, h, hh, observed) per observation from a
    ppc_intervals / ppc_ribbon figure.

    Trace order (ppc.py): 0 = outer interval, 1 = inner interval, 2 = median,
    3 = observed.  ppc_ribbon draws the intervals as polygons
    y = [hi, lo[::-1]]; ppc_intervals as vertical segments
    y = [lo_0, hi_0, None, lo_1, hi_1, None, ...].  Rows are sorted by x.
    """
    n = len(Y)

    def lo_hi(trace):
        v = np.asarray([np.nan if t is None else t for t in trace.y], dtype=float)
        if trace.fill == "toself":
            return v[n:][::-1], v[:n]
        return v[0::3], v[1::3]

    ll, hh = lo_hi(fig.data[0])
    l, h = lo_hi(fig.data[1])
    med = np.asarray(fig.data[2].y, dtype=float)
    obs = np.asarray(fig.data[3].y, dtype=float)
    return ll, l, med, h, hh, obs


def _reflected_kde_1d(data, xs):
    """Scott-bandwidth Gaussian KDE (s = std(ddof=1) * n**(-1/5)) of values in
    [0, 1], reflected at 0 and 1 (bayesplot's boundary correction): the
    sample is augmented with -x and 2-x and normalised by the original n.
    Used to tie the PIT values recomputed here to the curve the figure
    actually plots."""
    data = np.asarray(data, dtype=float)
    n = len(data)
    s = np.std(data, ddof=1) * n ** (-0.2)
    pts = np.concatenate([data, -data, 2.0 - data])
    z = (np.asarray(xs, dtype=float)[:, None] - pts[None, :]) / s
    return np.exp(-0.5 * z * z).sum(axis=1) / (n * s * np.sqrt(2.0 * np.pi))


def _bf_loo_pit(reff=None):
    """Recompute the PIT vector exactly as ppc_loo_pit does when
    log_likelihood is given (same _psis_weights code path, reff default 1.0,
    per-observation weight normalization, `<=` indicator)."""
    pit = np.empty(len(Y), dtype=np.float64)
    for i in range(len(Y)):
        log_w, _ = _psis_weights(LL[:, i], reff=1.0 if reff is None else reff)
        w = np.exp(np.asarray(log_w, dtype=np.float64))
        w /= w.sum()
        pit[i] = float(np.sum(w * (YREP[:, i] <= Y[i])))
    return pit


# ---------------------------------------------------------------------------
# 1/2. intervals & ribbon (bayesplot ppc_intervals_data / ppc_ribbon_data,
#      prob=0.5, prob_outer=0.9 -> type-7 quantiles 5/25/50/75/95 %)
# ---------------------------------------------------------------------------

def _check_intervals_vs_ref(fig, ref_key):
    # ppc_intervals sorts rows by x; the reference is in observation order
    # (obs_index 1..30), so align the reference with argsort(x).
    xo = np.argsort(X)
    assert np.asarray(fig.data[2].x, dtype=float) == pytest.approx(X[xo])
    ll, l, m, h, hh, obs = _interval_bounds(fig)
    ref = RC[ref_key]
    np.testing.assert_allclose(ll, np.array(ref["ll"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(l, np.array(ref["l"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(m, np.array(ref["m"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(h, np.array(ref["h"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(hh, np.array(ref["hh"])[xo], rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(obs, Y[xo], rtol=RTOL, atol=ATOL)


def test_ppc_intervals_matches_bayesplot_intervals_data():
    fig = ppc.ppc_intervals(Y, YREP, x=X, prob=0.5, prob_outer=0.9)
    _check_intervals_vs_ref(fig, "intervals")


def test_ppc_ribbon_matches_bayesplot_ribbon_data():
    # ppc_ribbon_data uses the same .ppd_intervals_data bounds as intervals.
    fig = ppc.ppc_ribbon(Y, YREP, x=X, prob=0.5, prob_outer=0.9)
    _check_intervals_vs_ref(fig, "ribbon")


