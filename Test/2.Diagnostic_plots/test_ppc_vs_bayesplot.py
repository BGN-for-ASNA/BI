    np.testing.assert_allclose(np.asarray(rep.y, float),
                               np.array(RC["stat_sd_yrep"]), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(np.asarray(obs.x, float), [RC["stat_mean_y"]],
                               rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(np.asarray(obs.y, float), [RC["stat_sd_y"]],
                               rtol=RTOL, atol=ATOL)


