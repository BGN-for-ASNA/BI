# 10. ppc_rootogram (bayesplot ppc_rootogram, style="hanging", prob=0.9)
# ---------------------------------------------------------------------------

def test_ppc_rootogram():
    fig = ppc.ppc_rootogram(CY, CYREP)
    bar, curve = fig.data
    ref = RCOUNT["rootogram"]
    np.testing.assert_allclose(np.asarray(bar.x, float), np.array(ref["xpos"]),
                               rtol=RTOL, atol=ATOL)
    # hanging bars: height sqrt(observed), based at sqrt(expected) - sqrt(observed)
    np.testing.assert_allclose(np.asarray(bar.y, float),
                               np.array(ref["sqrt_observed"]), rtol=RTOL, atol=ATOL)
    np.testing.assert_allclose(np.asarray(bar.base, float),
                               np.array(ref["sqrt_expected"]) - np.array(ref["sqrt_observed"]),
                               rtol=RTOL, atol=ATOL)
    # expected curve: sqrt(colMeans(counts))
    np.testing.assert_allclose(np.asarray(curve.y, float),
                               np.array(ref["sqrt_expected"]), rtol=RTOL, atol=ATOL)


