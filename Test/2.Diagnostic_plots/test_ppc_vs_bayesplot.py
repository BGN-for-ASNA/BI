# 7. ppc_error_hist (bayesplot ppc_error_hist: per-draw errors, faceted)
# ---------------------------------------------------------------------------

def test_ppc_error_hist_mean_residuals():
    # BF plots ONE histogram of the mean residuals r_i = y_i - E[yrep_i]; the
    # Histogram trace exposes those 30 values as x.  Mean of the reference
    # per-draw residuals over draws == y - colMeans(yrep) (exact arithmetic).
    fig = ppc.ppc_error_hist(Y, YREP)
    np.testing.assert_allclose(np.asarray(fig.data[0].x, float),
                               RESID.mean(axis=0), rtol=RTOL, atol=ATOL)


@pytest.mark.xfail(
    strict=True,
    reason=(
        "ppc_error_hist plots a single histogram of the 30 mean residuals "
        "y - E[yrep] (its Histogram trace exposes only those 30 values), while "
        "bayesplot ppc_error_hist uses per-draw errors y - yrep[s,i] "
        "(rstantools::predictive_error, 200x30, faceted per draw); the "
        "BayesForge figure exposes no per-draw residuals, so the figure's 30 "
        "mean residuals cannot equal the reference error_hist_resid (200x30)."
    ),
)
def test_ppc_error_hist_per_draw_residuals():
    fig = ppc.ppc_error_hist(Y, YREP)
    np.testing.assert_allclose(np.asarray(fig.data[0].x, float), RESID,
                               rtol=RTOL, atol=ATOL)


# ---------------------------------------------------------------------------
# 8. ppc_density (exact KDE match skipped: BF uses Scott's rule and samples
#    n draws with seed 0, bayesplot uses nrd0 on all draws -- see README).
#    Only structural facts are checked: n yrep lines + one observed-y trace
#    whose x grid is built from the data and spans the observed range.
# ---------------------------------------------------------------------------

def test_ppc_density_traces():
    n = 50  # draws passed (== ppc.py default); yrep has 200 rows
    fig = ppc.ppc_density(Y, YREP, n=n)
    names = [t.name for t in fig.data]
    assert len(fig.data) == n + 1
    assert names[:n] == ["Predictions of y"] * n   # n yrep KDE lines
    assert names[n] == "y (observed)"              # observed-y trace built from y
    xs = np.asarray(fig.data[-1].x, dtype=float)
    # shared evaluation grid, built from y (and the sampled yrep): it covers
    # the observed data range for this fixture
    for t in fig.data:
        np.testing.assert_array_equal(np.asarray(t.x, dtype=float), xs)
    assert xs[0] <= Y.min()
    assert xs[-1] >= Y.max()
    ys = np.asarray(fig.data[-1].y, dtype=float)
    assert np.isfinite(ys).all() and (ys > 0).all()


# ---------------------------------------------------------------------------
# 9. ppc_boxplot (ggplot2 stat_boxplot quantile.type=7: Q1/median/Q3)
#
# BF samples 20 of the 200 draws with np.random.default_rng(0) (the seed-0
# sample includes draws 3 and 7, 0-based), so the reference yrep_1..yrep_10
# rows do NOT line up with the figure series in general.  Each go.Box trace
# exposes its raw series as y, so: check every series' type-7 quartiles
# against np.percentile of that series' raw values AND against the raw yrep
# row, and check the sampled draws that ARE in the reference (yrep_4,
# yrep_8) plus the observed series against the reference quartiles.
# ---------------------------------------------------------------------------

def test_ppc_boxplot_quartiles():
    fig = ppc.ppc_boxplot(Y, YREP)            # n=20 default
    assert len(fig.data) == 21
    assert fig.data[0].name == "observed"     # observed box first, then predictions
    qy = np.percentile(np.asarray(fig.data[0].y, dtype=float), [25, 50, 75])
    np.testing.assert_allclose(qy, np.array(RC["boxplot"]["y"]), rtol=RTOL, atol=ATOL)

    # ppc_boxplot samples its 20 draws with default_rng(0), in this order
    idx = np.random.default_rng(0).choice(len(YREP), size=20, replace=False)
    n_ref_checked = 0
    for s, t in zip(idx, fig.data[1:]):
        vals = np.asarray(t.y, dtype=float)
        np.testing.assert_allclose(vals, YREP[s], rtol=RTOL, atol=ATOL)
        q = np.percentile(vals, [25, 50, 75])
        np.testing.assert_allclose(q, np.percentile(YREP[s], [25, 50, 75]),
                                   rtol=RTOL, atol=ATOL)
        key = f"yrep_{s + 1}"                 # reference covers draws 1..10 (1-based)
        if key in RC["boxplot"]:
            np.testing.assert_allclose(q, np.array(RC["boxplot"][key]),
                                       rtol=RTOL, atol=ATOL)
            n_ref_checked += 1
    assert n_ref_checked == 2                 # draws 3 and 7 (0-based) sampled


