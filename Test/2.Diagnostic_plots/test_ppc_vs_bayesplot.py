# 5. ppc_stat_2d (stat1="mean", stat2="sd")
# ---------------------------------------------------------------------------

def test_ppc_stat_2d_mean_sd():
    fig = ppc.ppc_stat_2d(Y, YREP, stat1="mean", stat2="sd")
    rep = fig.data[0]   # (mean(yrep[s]), sd(yrep[s])) per draw, all 200
    obs = fig.data[1]   # observed point
